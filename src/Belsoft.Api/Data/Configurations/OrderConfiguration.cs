using Belsoft.Api.Models;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace Belsoft.Api.Data.Configurations;

public sealed class OrderConfiguration : IEntityTypeConfiguration<Order>
{
    // Seed rows need a fixed date: a "now" here would change on every build and produce a new migration each time.
    private static readonly DateTimeOffset SeedCreatedAt = new(2026, 1, 1, 0, 0, 0, TimeSpan.Zero);

    public void Configure(EntityTypeBuilder<Order> builder)
    {
        builder.ToTable("Orders", table =>
        {
            table.HasCheckConstraint(                                                               // ①
                "CK_Orders_Status",
                "[Status] IN (N'Pending', N'Submitted', N'Paid', N'Shipped', N'Cancelled')");
            table.HasCheckConstraint("CK_Orders_CustomerName_NotBlank", "LEN([CustomerName]) > 0");
        });

        builder.HasKey(order => order.Id);

        builder.Property(order => order.CustomerName)
            .HasMaxLength(100)
            .IsRequired();

        builder.Property(order => order.Status)
            .HasConversion<string>()
            .HasMaxLength(20);

        builder.Property(order => order.CreatedAt);

        // SQL Server rowversion: changes on every UPDATE; EF Core adds it to the WHERE of every UPDATE/DELETE.
        builder.Property(order => order.RowVersion)
            .IsRowVersion();                                                                        // ②

        // Serves the list endpoint's most common shape: filter by Status, newest first. Measured in L08.
        builder.HasIndex(order => new { order.Status, order.CreatedAt })
            .HasDatabaseName("IX_Orders_Status_CreatedAt");

        builder.HasMany(order => order.Lines)
            .WithOne()
            .HasForeignKey("OrderId")                                                               // ③
            .OnDelete(DeleteBehavior.Cascade);

        // EF Core fills and reads the private list directly, never through the read-only property.
        builder.Navigation(order => order.Lines)
            .HasField("_lines")
            .UsePropertyAccessMode(PropertyAccessMode.Field);                                       // ④

        // Ids 1–3 as since L01. RowVersion is generated by SQL Server, so seeds don't supply it.
        builder.HasData(
            new { Id = 1, CustomerName = "Ada Lovelace", Status = OrderStatus.Pending, CreatedAt = SeedCreatedAt },
            new { Id = 2, CustomerName = "Alan Turing", Status = OrderStatus.Paid, CreatedAt = SeedCreatedAt },
            new { Id = 3, CustomerName = "Grace Hopper", Status = OrderStatus.Pending, CreatedAt = SeedCreatedAt });
    }
}